def _is_ast_node(value: Any) -> bool:
    """True if *value* is an Infra AST node (needs recursive evaluation)."""
    return hasattr(value, "__class__") and getattr(
        value.__class__, "__module__", ""
    ).startswith("infra.parser")


def evaluate_expression(expr: Optional[n.Expression], context: CompileContext) -> Any:
    """Evaluate an AST expression to a Python value using the compile context.

    Supports literals, units, identifiers (resolved from context variables),
    template strings, binary operators, lists, maps and builtin calls. Unknown
    identifiers collapse to a ``${NAME}`` placeholder so backends emit a
    runtime-reference rather than crashing.
    """
    if expr is None:
        return None
    if isinstance(expr, n.Literal):
        return expr.value
    if isinstance(expr, n.Duration):
        return evaluate_duration(expr)
    if isinstance(expr, n.ResourceValue):
        return evaluate_resource(expr, "kubernetes")
    if isinstance(expr, n.Percentage):
        return f"{expr.value}%"
    if isinstance(expr, n.Identifier):
        if expr.name in context.variables:
            value = context.variables[expr.name]
            if _is_ast_node(value):
                return evaluate_expression(value, context)
            return value
        return f"${{{expr.name}}}"
    if isinstance(expr, n.TemplateString):
        parts = []
        for part in expr.parts:
            if isinstance(part, str):
                parts.append(part)
            elif isinstance(part, tuple) and part and part[0] == "expr":
                # raw expression source stored by the transformer
                from infra.parser import parse_expression  # local import

                sub = parse_expression(part[1])
                val = evaluate_expression(sub, context)
                parts.append(str(val) if val is not None else "")
            else:
                val = evaluate_expression(part, context)
                parts.append(str(val) if val is not None else "")
        return "".join(parts)
    if isinstance(expr, n.List):
        return [evaluate_expression(i, context) for i in expr.items]
    if isinstance(expr, n.Map):
        return {
            evaluate_expression(e.key, context): evaluate_expression(e.value, context)
            for e in expr.entries
        }
    if isinstance(expr, n.BinaryOp):
        left = evaluate_expression(expr.left, context)
        right = evaluate_expression(expr.right, context)
        op = expr.operator
        try:
            if op == "+":
                return left + right
            if op == "-":
                return left - right
            if op == "*":
                return left * right
            if op == "/":
                return left / right
            if op == "==":
                return left == right
            if op == "!=":
                return left != right
        except Exception as exc:  # noqa: BLE001 - lenient eval, log for diag
            logger.debug("binary eval failed (op=%s, l=%r, r=%r): %s",
                         getattr(expr, "operator", None), left, right, exc)
            return None
    if isinstance(expr, n.Call):
        return _eval_builtin(expr, context)
    return None


def _eval_builtin(expr: n.Call, context: CompileContext) -> Any:
    callee = expr.callee.name if isinstance(expr.callee, n.Identifier) else ""
    args = [evaluate_expression(a, context) for a in expr.args]
    try:
        from infra.stdlib.functions import call_builtin

        if callee in (
            "env",
            "upper",
            "lower",
            "trim",
            "replace",
            "contains",
            "starts_with",
            "ends_with",
            "split",
            "join",
            "len",
            "min",
            "max",
            "abs",
            "clamp",
            "length",
            "concat",
            "first",
            "last",
            "range",
            "coalesce",
            "if_env",
        ):
            return call_builtin(callee, args)
    except Exception as exc:  # noqa: BLE001 - lenient eval, log for diag
        logger.debug("builtin eval failed (callee=%r): %s", callee, exc)
    if callee == "secret":
        return args[0] if args else None
    if callee == "config":
        return args[0] if args else None
    if callee == "version":
        return args[0] if args else None
    return None


def evaluate_duration(d: n.Duration) -> str:
    """Return a duration as a compact string (e.g. Duration(30,'s') -> '30s')."""
    value = d.value
    if value == int(value):
        return f"{int(value)}{d.unit}"
    return f"{value}{d.unit}"


def evaluate_resource(r: n.ResourceValue, format: str = "kubernetes") -> str:
    """Render a resource value for a given target format."""
    if format == "kubernetes":
        return r.to_kubernetes()
    if format == "docker":
        return str(r.to_bytes())
    return r.to_kubernetes()
